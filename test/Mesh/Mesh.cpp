XMMATRIX Mesh::GetWorldMatrix() {
    // 缩放
    XMMATRIX scaleX = XMMatrixScaling(
        scale.x,
        scale.y,
        scale.z
    );
    // 旋转
    XMMATRIX rotationX = XMMatrixRotationRollPitchYaw(
        XMConvertToRadians(rotation.x),
        XMConvertToRadians(rotation.y),
        XMConvertToRadians(rotation.z)
    );
    // 位移
    XMMATRIX translation = XMMatrixTranslation(
        position.x,
        position.y,
        position.z
    );
    // World = Scale * Rotation * Translation
    return scaleX * rotationX * translation;
}

void Mesh::Rotate(float x, float y, float z) {
    rotation.x += x;
    rotation.y += y;
    rotation.z += z;
}

XMFLOAT3 Mesh::Getfacing() {
    XMVECTOR defaultFacing = XMLoadFloat3(&facing);
    XMVECTOR result = XMVector3TransformNormal(defaultFacing, GetWorldMatrix());

    XMFLOAT3 resultFloat;
    XMStoreFloat3(&resultFloat, XMVector3Normalize(result));

    return resultFloat;
}

void Mesh::Move(bool forward) {
    XMFLOAT3 dir = Getfacing();

    XMVECTOR pos = XMLoadFloat3(&position);
    XMVECTOR direction = XMLoadFloat3(&dir);

    if (forward)
    {
        pos += direction * 0.1f;
    }
    else
    {
        pos -= direction * 0.1f;
    }

    XMStoreFloat3(&position, pos);
}
